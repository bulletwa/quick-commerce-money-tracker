// Generates src/components/art/icon-data.ts from the Phosphor icon set (MIT, node_modules/@phosphor-icons/core).
// Only the icons we use are inlined, so nothing is fetched at runtime. Re-run after changing the list: node scripts/build-icons.mjs
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const dir = path.join(root, "node_modules/@phosphor-icons/core/assets/regular");
const names = [
  "t-shirt", "bread", "coffee", "bowl-food", "egg", "bowl-steam", "broom", "cheese", "cake", "ice-cream", "cookie", "acorn", "plug", "snowflake",
  "carrot", "wrench", "pill", "cooking-pot", "fork-knife", "watch", "fish", "sparkle", "pizza", "hamburger", "flower-lotus", "pepper", "popcorn",
  "grains", "gift", "cigarette", "basket", "shopping-bag", "receipt", "calendar-blank", "funnel", "download-simple", "upload-simple", "trash",
  "check-circle", "warning", "caret-down", "caret-right", "x", "magnifying-glass", "arrows-clockwise", "coins", "tag", "storefront", "wine", "palette", "lightbulb", "flame", "arrow-up", "arrow-down",
];
const out = {};
for (const n of names) {
  const svg = fs.readFileSync(path.join(dir, `${n}.svg`), "utf8");
  const inner = svg.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
  if (/<script|on\w+=|href=/i.test(inner)) throw new Error(`unexpected markup in ${n}`);
  out[n] = inner;
}
const body = `// GENERATED by scripts/build-icons.mjs from Phosphor Icons (MIT, https://github.com/phosphor-icons/core). Do not edit by hand.\nexport const ICON_DATA: Record<string, string> = ${JSON.stringify(out, null, 1)};\n`;
fs.writeFileSync(path.join(root, "src/components/art/icon-data.ts"), body);
console.log(`wrote ${names.length} icons, ${(body.length / 1024).toFixed(1)} KB`);
